// 01-addresses.c — «память как лента байтов»: & / * / **, sizeof указателя и того, что за ним.
// Тема: указатель — это просто число (адрес), *p идёт по этому числу.
// Сборка/запуск — в README.md этой папки.

#include <stdio.h>
#include <stdlib.h>

static int n_fail = 0;

static void check (int cond, const char *what) {
    if (!cond) {
        ++n_fail;
        printf ("FAIL: %s\n", what);
    }
}

int main (void) {
    int x = 42;
    int *p = &x;    // p — ячейка, в которой записан адрес x
    int **pp = &p;  // pp — ячейка, в которой записан адрес p

    printf ("адрес x  = %p\n", (void *) &x);
    printf ("p хранит = %p\n", (void *) p);
    printf ("pp хранит = %p\n", (void *) pp);

    check (*p == 42, "*p читает 42 — x лежит по адресу, записанному в p");
    check (**pp == 42, "**pp читает 42 — двойное разыменование доходит до x");

    *p = 100;
    check (x == 100, "после *p = 100 исходный x изменился: запись прошла «сквозь» указатель");

    **pp = 777;
    check (x == 777, "после **pp = 777 x снова изменился: ** пишет туда, куда смотрит p");

    int y = 5;
    p = &y;        // перекинули p на другую ячейку
    **pp = 9;
    check (y == 9, "p перекинули на y — теперь **pp пишет уже в y");
    check (p == &y && x == 777, "p переключили на y: x остался старый, а все записи с этого момента идут в y");

    check (sizeof p == 8, "sizeof указателя на x86-64 = 8 байт");
    check (sizeof *p == 4, "sizeof *p = 4: то, куда смотрит указатель, — это int");
    check (sizeof pp == 8, "указатель на указатель тоже 8 байт — внутри лежит адрес, не данные");

    if (n_fail == 0) {
        printf ("OK: все проверки (01). Запомни: **pp = v — это запись v в ту ячейку, куда смотрит p.\n");
    } else {
        printf ("ОТКАЗ: не прошли %d проверок (01)\n", n_fail);
    }
    return n_fail == 0 ? 0 : 1;
}
