// 02-array-decay.c — массив против указателя: sizeof, &a, &a[0] и «потерянная» длина в функции.
// Тема: массив — это данные; в выражении он почти всегда распадается в указатель на первый элемент.
// Сборка/запуск — в README.md этой папки.

#include <stdio.h>
#include <stdlib.h>
#include <stddef.h>

static int n_fail = 0;

static void check (int cond, const char *what) {
    if (!cond) {
        ++n_fail;
        printf ("FAIL: %s\n", what);
    }
}

// Ловушка из SPRAVOCHNIK.md §3.2. Два «эквивалентных» объявления:
//     void f (int arr[100])   // «красная тряпка»: [100] никого ни о чём не информирует
//     void f (int *arr)       // честная запись — внутри функция видит ТОЛЬКО указатель
// gcc сам ругается на sizeof arr в первом варианте (-Wsizeof-array-argument).
static size_t size_reported_inside;
void f (int *arr) {
    size_reported_inside = sizeof arr;    // 8 — указатель. Свойства массива сюда не приехали.
    (void) arr;
}

int main (void) {
    int a[4] = {1, 2, 3, 4};

    check (sizeof a == 16, "sizeof a = 16: массив целиком — 4 по 4 байта");
    check ((void *) &a == (void *) &a[0], "по значению &a и &a[0] одинаковы (оба — начальный адрес); типы разные: указатель на весь массив против int *");

    check (sizeof &a == 8, "sizeof &a = 8: это указатель (на массив целиком)");

    // Распад: здесь a в выражении стало int* на первый элемент.
    int *first = a;
    check (sizeof first == 8, "после распада sizeof = 8: указатель, а не массив");
    check (first == (int *) a, "куда смотрит first, совпадает с первым элементом a");

    // Главная граблина про функции:
    int b[7] = {9, 8, 7, 6, 5, 4, 3};
    // при передаче b в f остаётся только первый адрес; длина 7 «выпадает»
    f (b);
    check (size_reported_inside == 8, "внутри f sizeof arr = 8: функция видит указатель, сколько бы [N] там ни стояло");
    check (b[6] == 3, "сама память цела, но f о длине не может знать — её передают отдельным параметром");

    // Честная длина — пока массив снаружи и ещё не распался:
    size_t len_b = sizeof b / sizeof b[0];
    check (len_b == 7, "sizeof b / sizeof b[0] = 7: длину читают снаружи, на функцию передают своим парам");

    if (n_fail == 0) {
        printf ("OK: все проверки (02). Массив = данные + длина. Указатель = данные БЕЗ длины.\n");
    } else {
        printf ("ОТКАЗ: не прошли %d проверок (02)\n", n_fail);
    }
    return n_fail == 0 ? 0 : 1;
}
