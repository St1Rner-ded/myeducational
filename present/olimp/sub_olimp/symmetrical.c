//Дано число от 0 до 9999 включительно. Если в числе меньше 4 знаков, то знаки слева - нули (например - 0011 или 0999)
//Задача - выяснить, симметричное ли число
//Разрешены только арифметические операции, запрещены сравнения, условные операторы

#include <stdio.h>

int main (void) {
    int n = 0;
    scanf ("%d", &n);
    int a = n % 10;
    int b = n / 10 % 10;
    int c = n / 100 % 10;
    int d = n / 1000 % 10;
    int m = 1000 * a + 100 * b + 10 * c + d;
    printf ("%d\n", n - m + 1);
    return 0;
}