// 04-matrix.c — int[2][3] это «массив из 2 строк»; десугаривание m[i][j] и плоский malloc.
// Тема: две модели двумерности: настоящий блок строк (int (*r)[3]) и массив указателей (int**).
// Сборка/запуск — в README.md этой папки.

#include <stdio.h>
#include <stdlib.h>

static int n_fail = 0;

static void check (int cond, const char *what) {
    if (!cond) {
        ++n_fail;
        printf ("FAIL: %s\n", what);
    }
}

int main (void) {
    int m[2][3] = { {1, 2, 3}, {4, 5, 6} };

    check (sizeof m == 24, "sizeof m = 24: 2 строки по 3 int, один непрерывный блок из 6 ячеек");
    check (sizeof m[0] == 12, "sizeof m[0] = 12: одна строка, а не один int");

    // Три эквивалентные записи одной и той же ячейки:
    check (m[1][2] == *(*(m + 1) + 2), "m[i][j] == *(*(m+i)+j): m+1 — сразу вторая строка (а не соседний int); +2 — шаг внутрь строки");
    check (m[1][2] == ((int *) m)[1 * 3 + 2], "m[i][j] == flat[i*СТОЛБЦОВ+j]: весь массив — одна плоская лента");

    // Указатель НА МАССИВ (строку): m распадается в int (*)[3], а не в int*.
    int (*row)[3] = m;
    check (row == &m[0], "row == &m[0]: одна и та же точка входа, но тип уже «указатель на строку из 3 int»");
    check ((*row)[2] == 3, "(*row)[2]: первая строка, третий элемент");
    row = row + 1;
    check ((*row)[0] == 4, "row + 1 прыгнул на 12 байт — сразу вторую строку, а не соседний int");
    check ((size_t) (((char *) (m + 1)) - ((char *) m)) == 12, "проверено в байтах: шаг между строками = 3 × 4 = 12");

    // Плоская динамическая матрица — то же самое, но руками на куче (см. SPRAVOCHNIK.md §3.5).
    size_t r = 2, c = 3;
    int *flat = malloc (r * c * sizeof(int));
    if (flat == NULL) {
        fprintf (stderr, "не вышло\n");
        return 1;
    }
    for (size_t i = 0; i < r; ++i) {
        for (size_t j = 0; j < c; ++j) {
            flat[i * c + j] = (int) (i * c + j);
        }
    }
    check (flat[0 * c + 2] == 2 && flat[1 * c + 2] == 5,
           "плоская матрица: элемент (i, j) лежит на позиции i * c + j");
    // int ** — это ДРУГая структура: массив из r указателей, за каждым — своя куча.
    // Не «та же матрица в другом виде»: это r раздельных malloc'ов и другая кэш-картина.
    free (flat);
    flat = NULL;

    if (n_fail == 0) {
        printf ("OK: все проверки (04). m — строки, слитые в одну линию; flat — та же разкладка руками.\n");
    } else {
        printf ("ОТКАЗ: не прошли %d проверок (04)\n", n_fail);
    }
    return n_fail == 0 ? 0 : 1;
}
